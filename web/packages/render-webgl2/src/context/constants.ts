const cache = new WeakMap<WebGL2RenderingContext, GLConstants>();

export const getGLConstants = (gl: WebGL2RenderingContext): GLConstants => {
    const cached = cache.get(gl);
    if (cached) return cached;
    const created = createConstantsFromGL(gl);
    cache.set(gl, created);
    return created;
};

export const createGLConstants = getGLConstants;
